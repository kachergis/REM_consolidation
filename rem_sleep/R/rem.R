# REM: Retrieving Effectively from Memory (Shiffrin & Steyvers, 1997).
# Item generation, episodic encoding, likelihood ratios, and recognition.

rem_par <- function(...) {
  p <- list(w = 20,        # content features per item
            g = .4,        # geometric base rate of feature values (environment = system)
            u_star = .04,  # probability of storing a feature per unit of study time
            t = 10,        # units of study time per presentation
            c = .7,        # probability that a stored feature is copied correctly
            crit = 0,      # old/new criterion on log odds (0 = odds of 1, the REM default)
            k_max = 3,     # cued recall: maximum number of traces sampled per cue
            acc_crit = 2,  # cued recall: log LR of cue match needed to accept a sampled trace
            rec_crit = .5) # cued recall: posterior an identified item needs to be output
  p <- modifyList(p, list(...))
  p$u <- 1 - (1 - p$u_star)^p$t  # probability a feature is stored during one presentation
  p
}

# REM feature values start at 1; R's rgeom() counts failures and starts at 0.
rgeom1 <- function(n, g) rgeom(n, g) + 1

gen_items <- function(n, w, g) matrix(rgeom1(n * w, g), n, w)

# Store `input` into `trace` wherever the trace is still empty (0): each empty feature is stored
# with probability u and, if stored, copied correctly with probability c (otherwise a random
# value is stored). Stored features are never overwritten.
encode <- function(trace, input, par, u = par$u) {
  empty <- which(trace == 0)
  stored <- empty[runif(length(empty)) < u]
  correct <- runif(length(stored)) < par$c
  trace[stored] <- ifelse(correct, input[stored], rgeom1(length(stored), par$g))
  trace
}

# log of the diagnosticity of a matching feature with value v:
# [c + (1-c) g(1-g)^(v-1)] / [g(1-g)^(v-1)]
log_match_ratio <- function(v, par) {
  pv <- par$g * (1 - par$g)^(v - 1)
  log((par$c + (1 - par$c) * pv) / pv)
}

# log likelihood ratio of each trace (row of `traces`) given a complete probe (S&S, 1997):
# lambda_j = (1-c)^n_jq * prod_v [match ratio(v)]^n_jvm, over the trace's non-zero features.
loglik <- function(probe, traces, par) {
  stopifnot(all(probe > 0), ncol(traces) == length(probe))
  match <- traces == rep(probe, each = nrow(traces))  # implies trace > 0, since probe > 0
  as.vector(match %*% (log_match_ratio(probe, par) - log(1 - par$c)) +
              rowSums(traces > 0) * log(1 - par$c))
}

# log likelihood that an (incomplete) stored trace was generated by each lexical item (row of
# `lex`), relative to a random item. Same form as loglik(), with the trace supplying the mask.
identify_loglik <- function(trace, lex, par) {
  f <- which(trace > 0)
  if (!length(f)) return(rep(0, nrow(lex)))
  match <- lex[, f, drop = FALSE] == rep(trace[f], each = nrow(lex))
  as.vector(match %*% (log_match_ratio(trace[f], par) - log(1 - par$c)) + length(f) * log(1 - par$c))
}

log_mean_exp <- function(x) {
  m <- max(x)
  m + log(mean(exp(x - m)))
}

# log odds that each probe (row) is old: log of the mean likelihood ratio over the store.
log_odds <- function(probes, store, par) {
  apply(probes, 1, function(p) log_mean_exp(loglik(p, store, par)))
}

# Hit rate, false-alarm rate and d' at the criterion, plus the criterion-free area under the ROC
# (P(old log odds > new log odds)). The log-linear correction (Hautus, 1995) keeps rates away
# from 0 and 1.
sdt <- function(old, new, crit = 0) {
  hr <- (sum(old > crit) + .5) / (length(old) + 1)
  fa <- (sum(new > crit) + .5) / (length(new) + 1)
  auc <- mean(outer(old, new, ">") + .5 * outer(old, new, "=="))
  c(hr = hr, fa = fa, dprime = qnorm(hr) - qnorm(fa), auc = auc)
}
